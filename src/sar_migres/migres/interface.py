from __future__ import annotations

from typing import Protocol, Any

class MigresRetrieverProvider(Protocol):
    """Contract consumed by the MIGRES control loop for retrieval and trace recording."""
    def retrieve_for(self, question: str, queries: list[str], known_info: list[str], missing_info: str = "") -> list[dict[str, Any]]: ...
    def record_filter(self, question: str, kept_doc_ids: list[str]) -> None: ...
    def finalize(self, question: str, final_evidence: list[str], final_missing: str) -> None: ...

class MigresBackendContract(Protocol):
    name: str
    def run_question(self, item: dict[str, Any], provider: MigresRetrieverProvider, llm: Any, run_id: str, workdir: Any): ...
    def describe(self) -> dict[str, Any]: ...
