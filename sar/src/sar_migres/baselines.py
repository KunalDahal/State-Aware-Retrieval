_TOK = re.compile(r"\w+", re.UNICODE)


class BaselineRetrievalStats:
    def __init__(self):
        self.n_queries = 0
        self.n_docs_scored = 0
        self.n_similarity_calcs = 0
        self.index_build_seconds = 0.0
        self.retrieval_seconds = 0.0

    def reset(self):
        self.__init__()
        return self

    def to_dict(self) -> dict[str, Any]:
        return self.__dict__.copy()


class BaselineRetriever(ABC):
    name: str = "baseline"
    score_name: str = "baseline_score"
    is_sar: bool = False

    def __init__(self):
        self.stats = BaselineRetrievalStats()

    @abstractmethod
    def retrieve(self, query: str, k: int) -> list[tuple[str, float]]:
        """Return ``[(doc_id, score)]`` in descending score order."""

    def retrieve_many(self, queries: Sequence[str], k: int) -> list[tuple[str, float]]:
        """Fuse the queries generated by MIGRES using the maximum per-document score.

        This is the key fix for baseline comparison: baselines are not a one-shot retrieval
        against the original question.  Every MIGRES-generated retrieval query is routed through
        the selected baseline retriever, then candidate scores are fused before Top-K selection.
        """
        clean = list(dict.fromkeys(q.strip() for q in queries if isinstance(q, str) and q.strip()))
        if not clean:
            return []
        merged: dict[str, float] = {}
        for q in clean:
            for did, score in self.retrieve(q, k):
                if did not in merged or score > merged[did]:
                    merged[did] = float(score)
        rows = sorted(merged.items(), key=lambda x: (-x[1], x[0]))[:k]
        return rows


# df must ACCUMULATE across flush batches (INSERT OR REPLACE kept only the last batch's count).
_DF_UPSERT = "INSERT INTO terms(term,df) VALUES(?,?) ON CONFLICT(term) DO UPDATE SET df = df + excluded.df"
_BM25_INDEX_VERSION = 2  # bump when the on-disk layout/contents change, so stale caches are rebuilt


class BM25Baseline(BaselineRetriever):
    name = "bm25"
    score_name = "bm25_score"

    def __init__(self, corpus: Corpus, k1: float = 0.9, b: float = 0.4,
                 cache_dir: str | Path = "data/cache/baselines"):
        super().__init__()
        self.corpus = corpus
        self.k1, self.b = float(k1), float(b)
        if self.k1 <= 0 or not (0 <= self.b <= 1):
            raise ConfigError("BM25 requires k1 > 0 and 0 <= b <= 1")
        self.cache_dir = Path(cache_dir)
        self._db = self.cache_dir / "bm25" / f"{_corpus_fingerprint(corpus)}-k1_{self.k1:g}-b_{self.b:g}-v{_BM25_INDEX_VERSION}.sqlite3"
        self._prepare_start = time.perf_counter()
        self._ensure_index()
        self.stats.index_build_seconds = time.perf_counter() - self._prepare_start

    def _connect(self):
        import sqlite3
        con = sqlite3.connect(self._db)
        con.execute("PRAGMA journal_mode=WAL")
        con.execute("PRAGMA synchronous=NORMAL")
        return con

    def _ensure_index(self):
        self._db.parent.mkdir(parents=True, exist_ok=True)
        if self._db.exists():
            try:
                with self._connect() as con:
                    n = int(con.execute("SELECT COUNT(*) FROM docs").fetchone()[0])
                    fp = con.execute("SELECT value FROM meta WHERE key='fingerprint'").fetchone()
                    if n == len(self.corpus) and fp and fp[0] == _corpus_fingerprint(self.corpus):
                        return
            except Exception:
                pass
            self._db.unlink(missing_ok=True)

        with self._connect() as con:
            con.executescript("""
                CREATE TABLE meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
                CREATE TABLE docs (row_idx INTEGER PRIMARY KEY, doc_id TEXT UNIQUE NOT NULL, doc_len INTEGER NOT NULL);
                CREATE TABLE terms (term TEXT PRIMARY KEY, df INTEGER NOT NULL);
                CREATE TABLE postings (term TEXT NOT NULL, row_idx INTEGER NOT NULL, tf INTEGER NOT NULL,
                                       PRIMARY KEY(term, row_idx));
                CREATE INDEX postings_term_idx ON postings(term);
            """)
            fp = _corpus_fingerprint(self.corpus)
            con.execute("INSERT INTO meta(key,value) VALUES('fingerprint',?)", (fp,))
            con.execute("INSERT INTO meta(key,value) VALUES('k1',?)", (str(self.k1),))
            con.execute("INSERT INTO meta(key,value) VALUES('b',?)", (str(self.b),))
            pending_postings, pending_terms = [], Counter()
            for row_idx, did in enumerate(self.corpus.ids):
                tf = Counter(_TOK.findall(self.corpus.get(did).embed_text().lower()))
                con.execute("INSERT INTO docs(row_idx,doc_id,doc_len) VALUES(?,?,?)", (row_idx, str(did), int(sum(tf.values()))))
                for term, freq in tf.items():
                    pending_postings.append((term, row_idx, int(freq)))
                    pending_terms[term] += 1
                if len(pending_postings) >= 20_000:
                    con.executemany("INSERT INTO postings(term,row_idx,tf) VALUES(?,?,?)", pending_postings)
                    pending_postings.clear()
                if row_idx % 2_000 == 0 and pending_terms:
                    con.executemany(_DF_UPSERT, pending_terms.items())
                    pending_terms.clear()
                    con.commit()
            if pending_postings:
                con.executemany("INSERT INTO postings(term,row_idx,tf) VALUES(?,?,?)", pending_postings)
            if pending_terms:
                con.executemany(_DF_UPSERT, pending_terms.items())
            con.commit()

    def retrieve(self, query: str, k: int) -> list[tuple[str, float]]:
        self.stats.n_queries += 1
        t0 = time.perf_counter()
        terms = list(dict.fromkeys(_TOK.findall(query.lower())))
        if not terms:
            return []
        with self._connect() as con:
            N = int(con.execute("SELECT COUNT(*) FROM docs").fetchone()[0])
            avgdl = float(con.execute("SELECT AVG(doc_len) FROM docs").fetchone()[0] or 0.0)
            scores: dict[int, float] = {}
            for term in terms:
                row = con.execute("SELECT df FROM terms WHERE term=?", (term,)).fetchone()
                if not row:
                    continue
                df = int(row[0])
                idf = math.log(1.0 + (N - df + 0.5) / (df + 0.5))
                for row_idx, tf, dl in con.execute(
                        "SELECT p.row_idx,p.tf,d.doc_len FROM postings p JOIN docs d ON d.row_idx=p.row_idx WHERE p.term=?",
                        (term,)):
                    f = float(tf)
                    denom = f + self.k1 * (1 - self.b + self.b * float(dl) / max(avgdl, 1e-9))
                    scores[int(row_idx)] = scores.get(int(row_idx), 0.0) + idf * f * (self.k1 + 1) / max(denom, 1e-12)
            if not scores:
                self.stats.retrieval_seconds += time.perf_counter() - t0
                return []
            ranked = sorted(scores.items(), key=lambda x: (-x[1], x[0]))[:k]
            out = []
            for row_idx, score in ranked:
                did = con.execute("SELECT doc_id FROM docs WHERE row_idx=?", (row_idx,)).fetchone()[0]
                out.append((str(did), float(score)))
            self.stats.n_docs_scored += len(scores)
            self.stats.n_similarity_calcs += len(scores) * len(terms)
        self.stats.retrieval_seconds += time.perf_counter() - t0
        return out



class MMRBaseline(BaselineRetriever):
    """Classic Maximal Marginal Relevance over a lexical BM25 candidate set.

    This baseline intentionally does not use sentence-transformers. BM25 supplies relevance and
    token-set Jaccard supplies the redundancy term. The implementation is an ordinary retriever
    that can occupy the same MIGRES retrieval slot as SAR.
    """
    name = "mmr"
    score_name = "mmr_score"

    def __init__(self, corpus: Corpus, cache_dir: str | Path, lambda_mult: float = 0.6,
                 candidate_multiplier: int = 10):
        super().__init__()
        if not 0.0 <= lambda_mult <= 1.0:
            raise ConfigError("MMR lambda must be in [0,1]")
        self.corpus = corpus
        self.lambda_mult = float(lambda_mult)
        self.candidate_multiplier = int(candidate_multiplier)
        self.first_stage = BM25Baseline(corpus, cache_dir=cache_dir)
        self.stats.index_build_seconds = self.first_stage.stats.index_build_seconds
        self._token_cache: dict[str, set[str]] = {}

    def _tokens(self, did: str) -> set[str]:
        if did not in self._token_cache:
            d = self.corpus.get(did)
            self._token_cache[did] = set(_TOK.findall((d.title + " " + d.text).lower()))
        return self._token_cache[did]

    @staticmethod
    def _jaccard(a: set[str], b: set[str]) -> float:
        u = a | b
        return len(a & b) / len(u) if u else 0.0

    def retrieve(self, query: str, k: int) -> list[tuple[str, float]]:
        self.stats.n_queries += 1
        t0 = time.perf_counter()
        pool = self.first_stage.retrieve(query, max(k, k * self.candidate_multiplier))
        if not pool:
            return []
        q_tokens = set(_TOK.findall(query.lower()))
        raw = np.asarray([s for _, s in pool], dtype=float)
        lo, hi = float(raw.min()), float(raw.max())
        rel = (raw - lo) / (hi - lo) if hi > lo else np.ones_like(raw)
        selected: list[int] = []
        remaining = set(range(len(pool)))
        target = min(k, len(pool))
        while remaining and len(selected) < target:
            best_i, best_score = None, -float("inf")
            for i in sorted(remaining):
                did = pool[i][0]
                redundancy = 0.0
                if selected:
                    redundancy = max(self._jaccard(self._tokens(did), self._tokens(pool[j][0])) for j in selected)
                score = self.lambda_mult * float(rel[i]) - (1.0 - self.lambda_mult) * redundancy
                if selected and not q_tokens:
                    score = -redundancy
                if score > best_score or (score == best_score and (best_i is None or str(did) < str(pool[best_i][0]))):
                    best_i, best_score = i, score
            assert best_i is not None
            selected.append(best_i); remaining.remove(best_i)
        self.stats.n_docs_scored += len(pool)
        self.stats.n_similarity_calcs += len(pool) * max(len(selected), 1)
        out = [(str(pool[i][0]), float(self.lambda_mult * rel[i])) for i in selected]
        self.stats.retrieval_seconds += time.perf_counter() - t0
        return out

class SentenceTransformerSearch(BaselineRetriever):
    name = "sentence_transformer_search"
    score_name = "cosine_score"

    def __init__(self, store: VectorStore, embedder: Embedder, chunk_size: int = 50_000, corpus: Corpus | None = None):
        super().__init__()
        self.store, self.embedder, self.chunk_size = store, embedder, int(chunk_size)
        self.corpus = corpus

    def retrieve(self, query: str, k: int) -> list[tuple[str, float]]:
        self.stats.n_queries += 1
        t0 = time.perf_counter()
        q = self.embedder.encode([query])
        best: list[tuple[float, str]] = []
        for _start, mat, _norms, ids in self.store.iter_chunks(self.chunk_size):
            s = cosine_matrix(q, mat)[0]
            self.stats.n_docs_scored += len(ids)
            self.stats.n_similarity_calcs += len(ids)
            for i in top_k_indices(s, k):
                best.append((float(s[i]), str(ids[int(i)])))
        best.sort(key=lambda x: (-x[0], x[1]))
        self.stats.retrieval_seconds += time.perf_counter() - t0
        return [(did, sc) for sc, did in best[:k]]


def _require_transformers():
    try:
        import torch
        import transformers
    except ImportError as e:
        raise DependencyMissingError(
            "this baseline needs torch + transformers, but not sentence-transformers; "
            "install 'sar-migres[migres]'"
        ) from e
    return torch, transformers


def _device(preferred: str = "") -> str:
    torch, _ = _require_transformers()
    if preferred:
        return preferred
    return "cuda" if torch.cuda.is_available() else "cpu"


def _corpus_fingerprint(corpus: Corpus) -> str:
    # Order-sensitive for speed; the corpus object already preserves stable input order.
    h = hashlib.sha256()
    for did in corpus.ids:
        h.update(did.encode("utf-8")); h.update(b"\0"); h.update(corpus.content_hashes[did].encode("ascii")); h.update(b"\n")
    return h.hexdigest()[:20]


class _DenseHFIndex(BaselineRetriever):
    model_name: str = ""
    normalize: bool = True

    def __init__(self, corpus: Corpus, cache_dir: str | Path, batch_size: int = 16, max_length: int = 384,
                 device: str = "", chunk_size: int = 50_000):
        super().__init__()
        self.corpus = corpus
        self.cache_dir = Path(cache_dir)
        self.batch_size = int(batch_size)
        self.max_length = int(max_length)
        self.device = _device(device)
        self.chunk_size = int(chunk_size)
        self.ids = corpus.ids
        self._fingerprint = _corpus_fingerprint(corpus)
        self._doc_vectors: np.memmap | np.ndarray | None = None
        self._query_encoder = None
        self.dim: int | None = None
        self._prepare_start = time.perf_counter()
        self._ensure_index()
        self.stats.index_build_seconds = time.perf_counter() - self._prepare_start

    def _load_encoder(self, model_name: str):
        torch, transformers = _require_transformers()
        tok = transformers.AutoTokenizer.from_pretrained(model_name)
        model = transformers.AutoModel.from_pretrained(model_name).to(self.device).eval()
        return tok, model

    def _encode_texts(self, texts: Sequence[str], tokenizer, model) -> np.ndarray:
        torch, _ = _require_transformers()
        rows = []
        with torch.no_grad():
            for s in range(0, len(texts), self.batch_size):
                batch = tokenizer(list(texts[s:s + self.batch_size]), padding=True, truncation=True,
                                  max_length=self.max_length, return_tensors="pt").to(self.device)
                out = model(**batch)
                if hasattr(out, "pooler_output") and out.pooler_output is not None:
                    x = out.pooler_output
                else:
                    x = out.last_hidden_state[:, 0]
                x = x.detach().float().cpu().numpy()
                if self.normalize:
                    x /= np.maximum(np.linalg.norm(x, axis=1, keepdims=True), 1e-12)
                rows.append(x.astype(np.float32))
        return np.vstack(rows) if rows else np.zeros((0, self.dim or 0), dtype=np.float32)

    def _doc_model(self):
        return self._load_encoder(self.model_name)

    def _query_model(self):
        return self._doc_model()

    def _cache_paths(self):
        key = hashlib.sha256(f"{self.__class__.__name__}|{self.model_name}|{_corpus_fingerprint(self.corpus)}".encode()).hexdigest()[:20]
        d = self.cache_dir / self.__class__.__name__ / key
        return d / "vectors.f32", d / "manifest.json"

    def _ensure_index(self):
        vec_path, man_path = self._cache_paths()
        if vec_path.exists() and man_path.exists():
            man = json.loads(man_path.read_text(encoding="utf-8"))
            if (man.get("model") == self.model_name and man.get("fingerprint") == self._fingerprint
                    and int(man.get("n_docs", -1)) == len(self.ids)):
                self.dim = int(man["dim"])
                self._doc_vectors = np.memmap(vec_path, mode="r", dtype=np.float32,
                                              shape=(len(self.ids), self.dim))
                return
        vec_path.parent.mkdir(parents=True, exist_ok=True)
        tok, model = self._doc_model()
        first = self._encode_texts(self.corpus.embed_texts(self.ids[: min(len(self.ids), self.batch_size)]), tok, model)
        self.dim = int(first.shape[1])
        mm = np.memmap(vec_path, mode="w+", dtype=np.float32, shape=(len(self.ids), self.dim))
        mm[:len(first)] = first
        for s in range(len(first), len(self.ids), self.batch_size):
            x = self._encode_texts(self.corpus.embed_texts(self.ids[s:s + self.batch_size]), tok, model)
            mm[s:s + len(x)] = x
        mm.flush()
        self._doc_vectors = np.memmap(vec_path, mode="r", dtype=np.float32, shape=(len(self.ids), self.dim))
        man_path.write_text(json.dumps({"model": self.model_name, "dim": self.dim,
                                        "n_docs": len(self.ids), "fingerprint": self._fingerprint}), encoding="utf-8")

    def _encode_query(self, query: str) -> np.ndarray:
        if self._query_encoder is None:
            self._query_encoder = self._query_model()
        tok, model = self._query_encoder
        return self._encode_texts([query], tok, model)

    def retrieve(self, query: str, k: int) -> list[tuple[str, float]]:
        self.stats.n_queries += 1
        t0 = time.perf_counter()
        q = self._encode_query(query)
        best: list[tuple[float, int]] = []
        for s in range(0, len(self.ids), self.chunk_size):
            e = min(s + self.chunk_size, len(self.ids))
            mat = np.asarray(self._doc_vectors[s:e])
            scores = mat @ q[0]
            self.stats.n_docs_scored += len(mat)
            self.stats.n_similarity_calcs += len(mat)
            for i in top_k_indices(scores, k):
                best.append((float(scores[int(i)]), s + int(i)))
        best.sort(key=lambda x: (-x[0], self.ids[x[1]]))
        self.stats.retrieval_seconds += time.perf_counter() - t0
        return [(self.ids[i], sc) for sc, i in best[:k]]


class DPRBaseline(_DenseHFIndex):
    name = "dpr"
    score_name = "dpr_dot_product"

    def __init__(self, corpus: Corpus, question_model: str, context_model: str, cache_dir: str | Path,
                 batch_size: int = 16, max_length: int = 384, device: str = "", chunk_size: int = 50_000):
        self.question_model_name = question_model
        self.model_name = context_model
        super().__init__(corpus, cache_dir, batch_size, max_length, device, chunk_size)

    def _doc_model(self):
        torch, transformers = _require_transformers()
        tok = transformers.DPRContextEncoderTokenizerFast.from_pretrained(self.model_name)
        model = transformers.DPRContextEncoder.from_pretrained(self.model_name).to(self.device).eval()
        self._dpr_tok, self._dpr_model = tok, model
        return tok, model

    def _query_model(self):
        torch, transformers = _require_transformers()
        tok = transformers.DPRQuestionEncoderTokenizerFast.from_pretrained(self.question_model_name)
        model = transformers.DPRQuestionEncoder.from_pretrained(self.question_model_name).to(self.device).eval()
        return tok, model


class ContrieverBaseline(_DenseHFIndex):
    name = "contriever"
    score_name = "contriever_dot_product"

    def __init__(self, corpus: Corpus, model_name: str, cache_dir: str | Path, batch_size: int = 16,
                 max_length: int = 384, device: str = "", chunk_size: int = 50_000):
        self.model_name = model_name
        super().__init__(corpus, cache_dir, batch_size, max_length, device, chunk_size)

    def _encode_texts(self, texts: Sequence[str], tokenizer, model) -> np.ndarray:
        torch, _ = _require_transformers()
        rows = []
        with torch.no_grad():
            for s in range(0, len(texts), self.batch_size):
                batch = tokenizer(list(texts[s:s + self.batch_size]), padding=True, truncation=True,
                                  max_length=self.max_length, return_tensors="pt").to(self.device)
                out = model(**batch).last_hidden_state
                mask = batch["attention_mask"].unsqueeze(-1).bool()
                x = (out * mask).sum(1) / mask.sum(1).clamp_min(1)
                x = x.detach().float().cpu().numpy()
                x /= np.maximum(np.linalg.norm(x, axis=1, keepdims=True), 1e-12)
                rows.append(x.astype(np.float32))
        return np.vstack(rows)


class SPLADEBaseline(BaselineRetriever):
    name = "splade"
    score_name = "splade_sparse_dot"

    def __init__(self, corpus: Corpus, model_name: str, cache_dir: str | Path, batch_size: int = 16,
                 max_length: int = 384, device: str = "", chunk_size: int = 1000):
        super().__init__()
        self.corpus, self.model_name = corpus, model_name
        self.cache_dir, self.batch_size, self.max_length = Path(cache_dir), int(batch_size), int(max_length)
        self.device, self.chunk_size = _device(device), int(chunk_size)
        self.ids = corpus.ids
        self._fingerprint = _corpus_fingerprint(corpus)
        self._prepare_start = time.perf_counter()
        self._shards = self._ensure_index()
        self._tok_model = None
        self.stats.index_build_seconds = time.perf_counter() - self._prepare_start

    def _load(self):
        if self._tok_model is not None:
            return self._tok_model
        torch, transformers = _require_transformers()
        tok = transformers.AutoTokenizer.from_pretrained(self.model_name)
        model = transformers.AutoModelForMaskedLM.from_pretrained(self.model_name).to(self.device).eval()
        self._tok_model = (tok, model)
        return self._tok_model

    def _encode_sparse(self, texts: Sequence[str], tok, model) -> sparse.csr_matrix:
        torch, _ = _require_transformers()
        chunks = []
        with torch.no_grad():
            for s in range(0, len(texts), self.batch_size):
                batch = tok(list(texts[s:s + self.batch_size]), padding=True, truncation=True,
                            max_length=self.max_length, return_tensors="pt").to(self.device)
                logits = model(**batch).logits
                vals = torch.log1p(torch.relu(logits)).max(dim=1).values.detach().float().cpu().numpy()
                for row in vals:
                    idx = np.flatnonzero(row > 0)
                    chunks.append(sparse.csr_matrix((row[idx], (np.zeros(len(idx), dtype=np.int32), idx)),
                                                     shape=(1, vals.shape[1]), dtype=np.float32))
        return sparse.vstack(chunks).tocsr() if chunks else sparse.csr_matrix((0, 0), dtype=np.float32)

    def _cache_root(self):
        key = hashlib.sha256(f"{self.model_name}|{_corpus_fingerprint(self.corpus)}".encode()).hexdigest()[:20]
        return self.cache_dir / "splade" / key

    def _ensure_index(self):
        root = self._cache_root(); root.mkdir(parents=True, exist_ok=True)
        meta = root / "manifest.json"
        if meta.exists():
            man = json.loads(meta.read_text(encoding="utf-8"))
            if man.get("fingerprint") == self._fingerprint and man.get("model") == self.model_name and int(man.get("n_docs", -1)) == len(self.ids):
                return [dict(x) for x in man["shards"]]
        tok, model = self._load()
        shards = []
        for s in range(0, len(self.ids), self.chunk_size):
            ids = self.ids[s:s + self.chunk_size]
            x = self._encode_sparse(self.corpus.embed_texts(ids), tok, model)
            path = root / f"docs-{s:09d}.npz"
            sparse.save_npz(path, x)
            shards.append({"start": s, "n": len(ids), "path": path.name, "dim": int(x.shape[1])})
        meta.write_text(json.dumps({"model": self.model_name, "n_docs": len(self.ids),
                                    "fingerprint": self._fingerprint, "shards": shards}), encoding="utf-8")
        return shards

    def retrieve(self, query: str, k: int) -> list[tuple[str, float]]:
        self.stats.n_queries += 1
        t0 = time.perf_counter()
        tok, model = self._load()
        q = self._encode_sparse([query], tok, model)
        best: list[tuple[float, str]] = []
        root = self._cache_root()
        for sh in self._shards:
            mat = sparse.load_npz(root / sh["path"]).tocsr()
            scores = (mat @ q.T).toarray().ravel()
            ids = self.ids[sh["start"]:sh["start"] + sh["n"]]
            self.stats.n_docs_scored += len(ids)
            self.stats.n_similarity_calcs += len(ids)
            for i in top_k_indices(scores, k):
                best.append((float(scores[int(i)]), str(ids[int(i)])))
        best.sort(key=lambda x: (-x[0], x[1]))
        self.stats.retrieval_seconds += time.perf_counter() - t0
        return [(did, sc) for sc, did in best[:k]]


class _ColBERTShardIndex:
    """Sharded variable-length token representation cache for ColBERT-style late interaction."""

    def __init__(self, corpus: Corpus, model_name: str, root: str | Path, batch_size: int, max_length: int,
                 max_doc_tokens: int, device: str, shard_docs: int = 1000):
        self.corpus, self.model_name = corpus, model_name
        self.root, self.batch_size, self.max_length = Path(root), int(batch_size), int(max_length)
        self.max_doc_tokens, self.device, self.shard_docs = int(max_doc_tokens), device, int(shard_docs)
        self.ids = corpus.ids
        self._fingerprint = _corpus_fingerprint(corpus)
        self.manifest_path = self.root / "manifest.json"
        self.shards: list[dict[str, Any]] = []
        self._build_or_load()

    def _load_model(self):
        torch, transformers = _require_transformers()
        tokenizer = transformers.AutoTokenizer.from_pretrained(self.model_name, trust_remote_code=True)
        # Current Transformers provides HF_ColBERT for this checkpoint. Fall back to AutoModel with remote code
        # for versions that expose the model through AutoModel but not the explicit class.
        try:
            cls = getattr(transformers, "HF_ColBERT")
            model = cls.from_pretrained(self.model_name, trust_remote_code=True).to(self.device).eval()
        except Exception:
            model = transformers.AutoModel.from_pretrained(self.model_name, trust_remote_code=True).to(self.device).eval()
        return tokenizer, model

    def _tokens(self, texts: Sequence[str], tokenizer, model) -> list[np.ndarray]:
        torch, _ = _require_transformers()
        out_rows: list[np.ndarray] = []
        with torch.no_grad():
            for s in range(0, len(texts), self.batch_size):
                batch = tokenizer(list(texts[s:s + self.batch_size]), padding=True, truncation=True,
                                  max_length=self.max_length, return_tensors="pt").to(self.device)
                out = model(**batch)
                x = getattr(out, "last_hidden_state", None)
                if x is None:
                    x = getattr(out, "embeddings", None)
                if x is None:
                    raise RuntimeError("ColBERT model output has no token-level representation")
                x = torch.nn.functional.normalize(x.float(), p=2, dim=-1).cpu().numpy()
                mask = batch["attention_mask"].cpu().numpy()
                for i in range(len(x)):
                    reps = x[i][mask[i].astype(bool)]
                    out_rows.append(reps[: self.max_doc_tokens].astype(np.float16))
        return out_rows

    def _build_or_load(self):
        key = hashlib.sha256(f"{self.model_name}|{_corpus_fingerprint(self.corpus)}|{self.max_doc_tokens}".encode()).hexdigest()[:20]
        root = self.root / key
        root.mkdir(parents=True, exist_ok=True)
        man_path = root / "manifest.json"
        if man_path.exists():
            man = json.loads(man_path.read_text(encoding="utf-8"))
            if man.get("fingerprint") == self._fingerprint and int(man.get("n_docs", -1)) == len(self.ids):
                self.root, self.manifest_path, self.shards = root, man_path, man["shards"]
                return
        tokenizer, model = self._load_model()
        shards = []
        for ss in range(0, len(self.ids), self.shard_docs):
            ids = self.ids[ss:ss + self.shard_docs]
            reps = self._tokens(self.corpus.embed_texts(ids), tokenizer, model)
            dim = reps[0].shape[1]
            lengths = np.asarray([len(x) for x in reps], dtype=np.int32)
            offsets = np.zeros(len(reps) + 1, dtype=np.int64)
            offsets[1:] = np.cumsum(lengths)
            tokens = np.concatenate(reps, axis=0) if len(reps) else np.zeros((0, dim), dtype=np.float16)
            ts = root / f"tokens-{ss:09d}.f16"
            om = root / f"offsets-{ss:09d}.npy"
            np.asarray(tokens, dtype=np.float16).tofile(ts)
            np.save(om, offsets)
            shard = {"start": ss, "n": len(ids), "dim": dim, "tokens": ts.name, "offsets": om.name}
            shards.append(shard)
        man_path.write_text(json.dumps({"model": self.model_name, "n_docs": len(self.ids),
                                        "fingerprint": self._fingerprint, "shards": shards}), encoding="utf-8")
        self.root, self.manifest_path, self.shards = root, man_path, shards

    def iter_docs(self):
        for shard in self.shards:
            offsets = np.load(self.root / shard["offsets"], mmap_mode="r")
            data = np.memmap(self.root / shard["tokens"], mode="r", dtype=np.float16,
                             shape=(int(offsets[-1]), int(shard["dim"])))
            ids = self.ids[shard["start"]:shard["start"] + shard["n"]]
            for i, did in enumerate(ids):
                a, b = int(offsets[i]), int(offsets[i + 1])
                yield str(did), np.asarray(data[a:b], dtype=np.float32)


class ColBERTv2Baseline(BaselineRetriever):
    name = "colbertv2"
    score_name = "colbert_maxsim"

    def __init__(self, corpus: Corpus, model_name: str, cache_dir: str | Path, batch_size: int = 16,
                 max_length: int = 384, query_max_tokens: int = 32, doc_max_tokens: int = 180,
                 device: str = "", chunk_size: int = 256):
        super().__init__()
        self.corpus, self.model_name = corpus, model_name
        self.device = _device(device)
        self.query_max_tokens = int(query_max_tokens)
        self._prepare_start = time.perf_counter()
        self.index = _ColBERTShardIndex(corpus, model_name, cache_dir, batch_size, max_length, doc_max_tokens, self.device)
        self._tokenizer, self._model = self.index._load_model()
        self.stats.index_build_seconds = time.perf_counter() - self._prepare_start
        self.chunk_size = int(chunk_size)

    def _query_tokens(self, query: str) -> np.ndarray:
        torch, _ = _require_transformers()
        with torch.no_grad():
            batch = self._tokenizer([query], padding=True, truncation=True, max_length=self.query_max_tokens,
                                    return_tensors="pt").to(self.device)
            out = self._model(**batch)
            x = getattr(out, "last_hidden_state", None)
            if x is None:
                x = getattr(out, "embeddings", None)
            if x is None:
                raise RuntimeError("ColBERT model output has no token representation")
            x = torch.nn.functional.normalize(x.float(), p=2, dim=-1).cpu().numpy()[0]
            mask = batch["attention_mask"].cpu().numpy()[0].astype(bool)
            return x[mask][: self.query_max_tokens].astype(np.float32)

    @staticmethod
    def _maxsim(q: np.ndarray, d: np.ndarray) -> float:
        if q.size == 0 or d.size == 0:
            return 0.0
        return float(np.max(q @ d.T, axis=1).sum())

    def retrieve(self, query: str, k: int) -> list[tuple[str, float]]:
        self.stats.n_queries += 1
        t0 = time.perf_counter()
        q = self._query_tokens(query)
        best: list[tuple[float, str]] = []
        for did, d in self.index.iter_docs():
            score = self._maxsim(q, d)
            best.append((score, did))
            self.stats.n_docs_scored += 1
            self.stats.n_similarity_calcs += len(q) * max(len(d), 1)
        best.sort(key=lambda x: (-x[0], x[1]))
        self.stats.retrieval_seconds += time.perf_counter() - t0
        return [(did, sc) for sc, did in best[:k]]



class InfoGainRAGBaseline(BaselineRetriever):
    """Adapter for the published InfoGain-RAG reranker.

    The paper's method relies on a specialized trained reranker. The public implementation does
    not expose a universally named inference checkpoint in its README, so this project requires
    the user to provide a compatible checkpoint path. No sentence-transformer dependency is used.
    BM25 is used only as the documented first-stage candidate retriever; the configured checkpoint
    supplies the information-gain ranking signal.
    """
    name = "infogain_rag"
    score_name = "infogain_rag_score"

    def __init__(self, corpus: Corpus, checkpoint: str, cache_dir: str | Path, candidate_k: int = 50,
                 batch_size: int = 16, max_length: int = 384, device: str = ""):
        super().__init__()
        if not checkpoint:
            raise ConfigError("baseline.infogain_checkpoint must point to a compatible InfoGain-RAG reranker checkpoint")
        self.corpus = corpus
        self.checkpoint = checkpoint
        self.candidate_k = int(candidate_k)
        self.batch_size = int(batch_size)
        self.max_length = int(max_length)
        self.device = _device(device)
        self.first_stage = BM25Baseline(corpus, cache_dir=cache_dir)
        self.stats.index_build_seconds = self.first_stage.stats.index_build_seconds
        self._tok = None
        self._model = None

    def _load(self):
        if self._model is not None:
            return
        torch, transformers = _require_transformers()
        self._tok = transformers.AutoTokenizer.from_pretrained(self.checkpoint)
        self._model = transformers.AutoModelForSequenceClassification.from_pretrained(self.checkpoint).to(self.device).eval()

    def retrieve(self, query: str, k: int) -> list[tuple[str, float]]:
        self.stats.n_queries += 1
        t0 = time.perf_counter()
        self._load()
        torch, _ = _require_transformers()
        candidates = self.first_stage.retrieve(query, max(k, self.candidate_k))
        if not candidates:
            return []
        pairs = []
        for did, _ in candidates:
            d = self.corpus.get(did)
            pairs.append(query)
            pairs.append(f"{d.title}. {d.text}" if d.title else d.text)
        scores = []
        with torch.no_grad():
            for s in range(0, len(candidates), self.batch_size):
                qs = pairs[2*s:2*min(s+self.batch_size, len(candidates))][0::2]
                ds = pairs[2*s:2*min(s+self.batch_size, len(candidates))][1::2]
                batch = self._tok(qs, ds, padding=True, truncation=True, max_length=self.max_length, return_tensors="pt").to(self.device)
                logits = self._model(**batch).logits
                values = logits[:, -1] if logits.ndim == 2 else logits.reshape(-1)
                scores.extend(values.float().cpu().tolist())
        order = sorted(range(len(candidates)), key=lambda i: (-float(scores[i]), candidates[i][0]))[:k]
        self.stats.n_docs_scored += len(candidates)
        self.stats.n_similarity_calcs += len(candidates)
        self.stats.retrieval_seconds += time.perf_counter() - t0
        return [(str(candidates[i][0]), float(scores[i])) for i in order]


def build_baseline(cfg, method: str, corpus: Corpus, *, store=None, embedder=None) -> BaselineRetriever:
    b = cfg.baseline
    if method == "bm25":
        return BM25Baseline(corpus, cache_dir=b.cache_dir)
    if method == "sentence_transformer_search":
        if store is None or embedder is None:
            raise ConfigError("sentence_transformer_search needs the SAR Sentence Transformer and vector store")
        return SentenceTransformerSearch(store, embedder, b.score_chunk_size, corpus=corpus)
    if method == "mmr":
        return MMRBaseline(corpus, cache_dir=b.cache_dir, lambda_mult=b.mmr_lambda, candidate_multiplier=b.mmr_candidate_multiplier)
    if method == "infogain_rag":
        return InfoGainRAGBaseline(corpus, checkpoint=b.infogain_checkpoint, cache_dir=b.cache_dir,
                                   candidate_k=b.infogain_candidate_k, batch_size=b.batch_size, max_length=b.max_length, device=cfg.embedding.device)
    if method == "dpr":
        return DPRBaseline(corpus, b.dpr_question_model, b.dpr_context_model, b.cache_dir, b.batch_size, b.max_length,
                            device=cfg.embedding.device, chunk_size=b.score_chunk_size)
    if method == "contriever":
        return ContrieverBaseline(corpus, b.contriever_model, b.cache_dir, b.batch_size, b.max_length,
                                  device=cfg.embedding.device, chunk_size=b.score_chunk_size)
    if method == "splade":
        return SPLADEBaseline(corpus, b.splade_model, b.cache_dir, b.batch_size, b.max_length,
                              device=cfg.embedding.device, chunk_size=b.score_chunk_size)
    if method == "colbertv2":
        return ColBERTv2Baseline(corpus, b.colbert_model, b.cache_dir, b.batch_size, b.max_length,
                                 b.colbert_query_max_tokens, b.colbert_doc_max_tokens, device=cfg.embedding.device, chunk_size=b.score_chunk_size)
    raise ConfigError(f"unknown baseline method {method!r}")


