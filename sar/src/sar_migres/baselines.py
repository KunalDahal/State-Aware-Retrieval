"""Operational baseline retrievers from methodology Table 5.6.

Each baseline satisfies the same small contract and can therefore replace SAR inside the
MIGRES search call.  None of the non-Sentence-Transformer baselines imports or requires the
``sentence-transformers`` package; they use native lexical, PyTorch/Transformers, sparse,
or late-interaction implementations instead.
"""
